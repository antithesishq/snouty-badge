//! File helpers shared by the host tests. The test binary's working
//! directory depends on how the build runs it, so relative paths are tried
//! under a few prefixes.
const std = @import("std");

const prefixes = [_][]const u8{ "", "carts/snouty-lynx/", "../", "../../" };

/// A file under the cart directory (`tests/roms/...`), or null.
pub fn read_cart_file(rel: []const u8, buf: []u8) ?[]u8 {
    for (prefixes) |pre| {
        var path_buf: [512]u8 = undefined;
        const path = std.fmt.bufPrint(&path_buf, "{s}{s}", .{ pre, rel }) catch continue;
        return std.Io.Dir.cwd().readFile(std.testing.io, path, buf) catch continue;
    }
    return null;
}

/// A file under $HOME (Adrian's local ROMs, `roms/lynx/x.lnx`), or null.
pub fn read_home_file(rel: []const u8, buf: []u8) ?[]u8 {
    const home = std.testing.environ.getPosix("HOME") orelse return null;
    var path_buf: [512]u8 = undefined;
    const path = std.fmt.bufPrint(&path_buf, "{s}/{s}", .{ home, rel }) catch return null;
    return std.Io.Dir.cwd().readFile(std.testing.io, path, buf) catch null;
}

/// Length of a 65SC02 instruction, or null for an opcode the 65SC02 does
/// not define (the Rockwell bit instructions, WAI/STP and the NOP holes).
/// Used only to check that a decrypted loader disassembles sanely.
pub fn op_len(op: u8) ?u8 {
    return switch (op) {
        // implied / accumulator (CMOS: INC A, DEC A, PHY, PLY, PHX, PLX)
        0x00, 0x08, 0x0A, 0x18, 0x28, 0x2A, 0x38, 0x40, 0x48, 0x4A, 0x58, 0x60, 0x68, 0x6A, 0x78, 0x88, 0x8A, 0x98, 0x9A, 0xA8, 0xAA, 0xB8, 0xBA, 0xC8, 0xCA, 0xD8, 0xE8, 0xEA, 0xF8, 0x1A, 0x3A, 0x5A, 0x7A, 0xDA, 0xFA => 1,
        // immediate (CMOS: BIT #)
        0x09, 0x29, 0x49, 0x69, 0xA0, 0xA2, 0xA9, 0xC0, 0xC9, 0xE0, 0xE9, 0x89 => 2,
        // zero page (CMOS: TSB, TRB, STZ)
        0x05, 0x06, 0x24, 0x25, 0x26, 0x45, 0x46, 0x65, 0x66, 0x84, 0x85, 0x86, 0xA4, 0xA5, 0xA6, 0xC4, 0xC5, 0xC6, 0xE4, 0xE5, 0xE6, 0x04, 0x14, 0x64 => 2,
        // zp,x / zp,y (CMOS: BIT zp,x, STZ zp,x)
        0x15, 0x16, 0x35, 0x36, 0x55, 0x56, 0x75, 0x76, 0x94, 0x95, 0xB4, 0xB5, 0xD5, 0xD6, 0xF5, 0xF6, 0x34, 0x74, 0x96, 0xB6 => 2,
        // (zp,x), (zp),y, (zp)
        0x01, 0x21, 0x41, 0x61, 0x81, 0xA1, 0xC1, 0xE1, 0x11, 0x31, 0x51, 0x71, 0x91, 0xB1, 0xD1, 0xF1, 0x12, 0x32, 0x52, 0x72, 0x92, 0xB2, 0xD2, 0xF2 => 2,
        // relative branches, BRA
        0x10, 0x30, 0x50, 0x70, 0x90, 0xB0, 0xD0, 0xF0, 0x80 => 2,
        // absolute (CMOS: TSB, TRB, STZ)
        0x0D, 0x0E, 0x20, 0x2C, 0x2D, 0x2E, 0x4C, 0x4D, 0x4E, 0x6D, 0x6E, 0x8C, 0x8D, 0x8E, 0xAC, 0xAD, 0xAE, 0xCC, 0xCD, 0xCE, 0xEC, 0xED, 0xEE, 0x0C, 0x1C, 0x9C => 3,
        // abs,x / abs,y (CMOS: BIT abs,x, STZ abs,x)
        0x1D, 0x1E, 0x3D, 0x3E, 0x5D, 0x5E, 0x7D, 0x7E, 0x9D, 0xBC, 0xBD, 0xDD, 0xDE, 0xFD, 0xFE, 0x3C, 0x9E, 0x19, 0x39, 0x59, 0x79, 0x99, 0xB9, 0xBE, 0xD9, 0xF9 => 3,
        // JMP (abs), JMP (abs,x)
        0x6C, 0x7C => 3,
        else => null,
    };
}
